#!/usr/bin/env python3
"""Generate repos.yaml: flowscripter repos, the packages they publish, their
dependency edges on each other, and a release order (upstream first).

  repos-graph.py            write repos.yaml
  repos-graph.py --check    exit 1 if repos.yaml is out of date

Reads package.json and Cargo.toml from each repo's default branch with the gh CLI.
"""
import base64
import json
import os
import re
import subprocess
import sys

ORG = "flowscripter"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "repos.yaml")
CFG = json.load(open(os.path.join(HERE, "repo-types.json")))
DEP_KEYS = ("dependencies", "devDependencies", "peerDependencies", "optionalDependencies")


def gh_json(path):
    p = subprocess.run(["gh", "api", path], capture_output=True, text=True)
    return json.loads(p.stdout) if p.returncode == 0 else None


def file_text(repo, path):
    j = gh_json("repos/%s/%s/contents/%s" % (ORG, repo, path))
    return base64.b64decode(j["content"]).decode() if j and "content" in j else None


def repos():
    p = subprocess.run(["gh", "api", "--paginate", "orgs/%s/repos?type=all&per_page=100" % ORG,
                        "--jq", ".[] | select(.archived | not) | select(.fork | not) | .name"],
                       capture_output=True, text=True, check=True)
    skip = set(CFG["ignore"])
    return sorted(n for n in p.stdout.split() if n not in skip)


def manifest(repo):
    """Returns (published package names, dependency names)."""
    names, deps = [], set()
    pkg = file_text(repo, "package.json")
    if pkg:
        j = json.loads(pkg)
        if j.get("name") and not j.get("private"):
            names.append(j["name"])
        for k in DEP_KEYS:
            deps |= set(j.get(k, {}))
    cargo = file_text(repo, "Cargo.toml")
    if cargo:
        m = re.search(r'(?ms)^\[package\].*?^name\s*=\s*"([^"]+)"', cargo)
        if m and not re.search(r"(?m)^publish\s*=\s*false", cargo):
            names.append(m.group(1))
        for section in re.findall(r"(?ms)^\[(?:dev-|build-)?dependencies\](.*?)(?=^\[|\Z)", cargo):
            deps |= set(re.findall(r"(?m)^([A-Za-z0-9_-]+)\s*=", section))
    return names, deps


def release_order(edges):
    order, done = [], set()

    def visit(n, stack=()):
        if n in done:
            return
        if n in stack:
            raise SystemExit("dependency cycle: " + " -> ".join(stack + (n,)))
        for d in sorted(edges[n]):
            visit(d, stack + (n,))
        done.add(n)
        order.append(n)
    for n in sorted(edges):
        visit(n)
    return order


def render(info, edges):
    lines = ["# Generated by scripts/repos-graph.py. Do not edit by hand; rerun the script.",
             "# depends_on lists flowscripter repos whose published packages this repo uses.",
             "repos:"]
    for n in sorted(info):
        lines.append("  %s:" % json.dumps(n))
        lines.append("    packages: %s" % json.dumps(info[n]))
        lines.append("    depends_on: %s" % json.dumps(sorted(edges[n])))
        lines.append("    dependents: %s" % json.dumps(sorted(m for m in edges if n in edges[m])))
    lines.append("release_order:")
    lines += ["  - %s" % json.dumps(n) for n in release_order(edges)]
    return "\n".join(lines) + "\n"


def main():
    manifests = {r: manifest(r) for r in repos()}
    owner = {p: r for r, (names, _) in manifests.items() for p in names}
    info = {r: names for r, (names, _) in manifests.items()}
    edges = {r: {owner[d] for d in deps if d in owner and owner[d] != r}
             for r, (_, deps) in manifests.items()}
    text = render(info, edges)
    if sys.argv[1:] == ["--check"]:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("repos.yaml is out of date: run scripts/repos-graph.py")
            return 1
        print("repos.yaml is up to date")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (%d repos)" % (os.path.relpath(OUT), len(info)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
